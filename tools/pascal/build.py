def write_batch(cfg, build, targets, compiler, extra, keep):
    """Assembler first where a module exists, then the compiler per target.

    Every step appends to a log INSIDE the mounted drive, because DOSBox-X is a
    GUI application and writes nothing to the host's stdout. The log is read
    back from the host afterwards.
    """
    comp = cfg["compiler"][compiler]
    tpc = machine("toolchain." + compiler, comp.get("exe"))
    log = cfg.get("log", "BUILD.LOG")
    lines = ["@echo off"]
    if not keep and cfg.get("wipe_tpu", True):
        # Wiping from the host and wiping inside DOSBox are two erasures, and
        # a fix that did only the first left stale .TPUs behind.
        lines.append("del *.TPU > NUL")
    lines.append("echo === build > %s" % log)

    asm = cfg["assembler"]
    if asm.get("exe") or asm.get("flags"):
        tasm = machine("toolchain.tasm", asm.get("exe"))
        out = (cfg.get("stage", {}) or {}).get("output")
        # Every directory holding .ASM: the build root, plus any staged
        # verbatim. ASSEMBLED FROM INSIDE ITS OWN DIRECTORY, because TASM
        # resolves INCLUDE against the current directory and one of these
        # modules includes a generated table. Passing `ASM\X.ASM` instead
        # would look for that table in the root and not find it.
        where = [(build, "")]
        for rel in (cfg.get("stage", {}) or {}).get("verbatim", []):
            d = build / pathlib.Path(rel).name.upper()
            if d.is_dir():
                where.append((d, d.name))
        for d, sub in where:
            for name in sorted(x.name for x in d.glob("*.ASM")):
                # BY PATH, WITH AN INCLUDE FLAG -- no `cd`. This used to change
                # into the directory and assemble a bare filename, on the
                # assumption that an assembler resolves INCLUDE against the
                # source file's own directory and so needed no help. MEASURED,
                # and it does not: `TASM ASM\\DEMOMATH.ASM` answers
                # `Can't locate file: COSTAB.INC` for an include sitting beside
                # the file that includes it. What it wants is the include flag,
                # and with `/IASM` the same command assembles cleanly.
                #
                # Worth having for what it deletes rather than what it adds: no
                # cd, no cd back, and no log path that has to know how deep the
                # batch currently is -- which is where a `..\\D:\\BUILD.LOG` that
                # DOS could not open silently swallowed every assembler message.
                src = ("%s\\%s" % (sub, name)) if sub else name
                inc = (" %s%s" % (asm.get("include_flag", "/I"), sub)) if sub else ""
                obj = (", %s\\%s" % (out, name.replace(".ASM", ".OBJ"))) if out else ""
                lines.append("echo. >> %s" % log)
                lines.append("echo ---- %s >> %s" % (src, log))
                lines.append("%s %s%s %s%s >> %s"
                             % (tasm, asm.get("flags", ""), inc, src, obj, log))
                lines.append("if errorlevel 1 echo ** FAILED >> %s" % log)
                lines.append("if not errorlevel 1 echo ** OK >> %s" % log)

    switches = (comp.get("switches", "") + extra).strip()
    for t in targets:
        for pre in comp.get("prepass", []):
            # A pass emitted immediately BEFORE a named target, with its own
            # switches. It exists for a circular unit reference: whichever unit
            # compiles first needs the other's .TPU, so one of them is built
            # once in a cut-down form for the other to compile against. It has
            # to sit here rather than at the top of the batch, because the
            # cut-down unit still needs everything below it in the order.
            if pre["before"] != t:
                continue
            lines.append("echo. >> %s" % log)
            lines.append("echo ---- %s (%s) >> %s"
                         % (pre["target"], pre.get("why", "prepass"), log))
            lines.append("%s %s %s %s >> %s"
                         % (tpc, switches, pre.get("switches", ""),
                            pre["target"], log))
        lines.append("echo. >> %s" % log)
        lines.append("echo ---- %s >> %s" % (t, log))
        lines.append("%s %s %s >> %s" % (tpc, switches, t, log))
        lines.append("if errorlevel 1 echo ** FAILED >> %s" % log)
        lines.append("if not errorlevel 1 echo ** OK >> %s" % log)
    lines.append("exit")
    (build / "BUILD.BAT").write_text("\r\n".join(lines) + "\r\n",
                                     encoding="ascii")


def write_conf(cfg, build, conf, compiler, root=None):
    """The DOSBox-X config, generated so no machine path is ever committed.

    `[dosbox.mount]` adds drives beyond the staging one: LETTER = "path",
    resolved against the project root. It exists so a session can reach a
    directory the build does NOT own -- a packaged demo, a folder of originals
    to run side by side -- without a machine path being typed into a committed
    file or a drive being mounted by hand every time.

    A missing directory is skipped with a line saying so, rather than mounted:
    DOSBox-X will mount a path that does not exist and then answer "Illegal
    command" for everything on it, which reads as the program being broken.
    """
    comp = cfg["compiler"][compiler]
    lines, doc = [], []
    for letter, rel in sorted((cfg.get("dosbox", {}).get("mount", {})).items()):
        d = (pathlib.Path(root) / rel) if root else pathlib.Path(rel)
        if d.is_dir():
            lines.append("mount %s %s" % (letter.upper(), d))
            doc.append("#     %s:  %s" % (letter.upper(), d))
        else:
            doc.append("#     %s:  NOT MOUNTED -- %s does not exist"
                       % (letter.upper(), d))
    conf.write_text(CONF_TEMPLATE.format(
        hdd=machine("dosbox.hdd"),
        build=str(build),
        drive=cfg.get("drive", "D"),
        title=cfg.get("title", "build"),
        binpath=bin_dir(cfg, compiler),
        mounts="".join(l + "\n" for l in lines),
        mountdoc="".join(l + "\n" for l in doc),
    ), encoding="ascii")


