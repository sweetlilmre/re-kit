# Ordering


USES = re.compile(r"(?is)\buses\b(.*?);")


def unit_deps(build, name83):
    """The 8.3 names a STAGED source depends on, from its `uses` clauses.

    Read from the staged copy, so the names have already been rewritten to
    their 8.3 form and match the filenames on disk. Units the compiler ships
    with -- Crt, Dos, System -- simply do not exist here and drop out.
    """
    p = build / name83
    if not p.exists():
        return []
    text = p.read_text(encoding="latin1", errors="replace")
    # strip comments, so a `uses` inside one cannot pull in a phantom
    text = re.sub(r"(?s)\{.*?\}|\(\*.*?\*\)", " ", text)
    out = []
    for clause in USES.findall(text):
        for word in re.split(r"[,\s]+", clause):
            cand = word.strip().upper()
            if cand and (build / (cand + ".PAS")).exists():
                out.append(cand + ".PAS")
    return out


def deps_first(build, sel):
    """`sel` plus everything it needs, units before the things that use them."""
    order, seen = [], set()

    def visit(name):
        if name in seen:
            return
        seen.add(name)
        for d in unit_deps(build, name):
            visit(d)
        order.append(name)

    for t in sel:
        visit(t)
    return order


def ordered(cfg, build, staged, selection):
    """The compile order, by whichever strategy the target declares.

    `uses` derives it from the staged sources and is right where the graph is
    the truth; `declared` takes the config's list verbatim and is right where a
    person has worked the order out against something the graph does not say --
    a circular reference broken by a bootstrap pass, for one.
    """
    sel = staged
    if selection:
        sel = [t for t in staged if t.split(".")[0] in selection]
        if not sel:
            raise SystemExit(
                "  no target matches %s; known: %s"
                % (selection, ", ".join(t.split(".")[0] for t in staged)))
    if cfg["order"]["mode"] == "declared":
        return sel
    return deps_first(build, sel)


