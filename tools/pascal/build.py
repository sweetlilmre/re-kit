def write_overlay(cfg, root, build, compiler, out):
    """An [autoexec]-only config: the mounts, the PATH, and where to land.

    WHY AN OVERLAY. A DOSBox config worth keeping is a few hundred tuned
    settings and nothing should regenerate those -- but the moment it also
    carries `mount D <somebody's checkout>` it is a committed file full of
    machine paths, which is what this project spent a ticket removing from two
    other files. Splitting it settles both: the settings stay committed and
    hand-edited, the mounts are generated from the answers file, and DOSBox-X is
    given both with -conf.

    THE OVERLAY GOES SECOND, and the design does not rest on knowing what
    DOSBox-X does with two [autoexec] sections. If it appends them, the base
    file's run first and the overlay's follow; if the later config wins outright,
    the overlay's are the only ones. Either way the overlay takes effect --
    because the base file's [autoexec] is kept empty of commands, which is the
    one thing that makes both behaviours the same. Do not put a command in it.

    Nothing is launched from here. The maintainer runs DOSBox; this writes the
    file and the caller prints the command.
    """
    comp = cfg["compiler"][compiler]
    dosbox = cfg.get("dosbox", {})
    lines = ["# GENERATED by kit/tools/pascal/build.py --interactive.",
             "# The settings live in the base config; this is the mounts alone,",
             "# so no machine path is ever committed. Do not edit it.",
             "",
             "[autoexec]",
             "mount C %s" % machine("dosbox.hdd"),
             "mount %s %s" % (cfg.get("drive", "D"), build)]
    for letter, rel in sorted(dosbox.get("mount", {}).items()):
        d = pathlib.Path(root) / rel
        if d.is_dir():
            lines.append("mount %s %s" % (letter.upper(), d))
        else:
            lines.append("REM %s: not mounted, %s does not exist"
                         % (letter.upper(), d))

    # The DOS-side bin directories, from the same answers the build compiles
    # with, so the interactive prompt cannot disagree with the build about which
    # compiler is installed. That disagreement is not theoretical: the committed
    # config put a TP bin directory on the PATH that had since been renamed, so
    # TPC at the prompt answered "Bad command or filename".
    path = [bin_dir(cfg, compiler)]
    try:
        tasm = machine("toolchain.tasm", cfg.get("assembler", {}).get("exe"))
        if tasm and ":" in tasm:
            path.append(tasm.rsplit(SEP, 1)[0])
    except project.Missing:
        pass
    path = [x for x in path if x]
    if path:
        lines.append("set PATH=%PATH%;" + ";".join(path))

    if dosbox.get("land"):
        lines.append("%s:" % dosbox["land"].rstrip(":").upper())
    for text in dosbox.get("banner", []):
        lines.append("echo." if not text else "echo   %s" % text)
    out.write_text(NL.join(lines) + NL, encoding="ascii")
    return out


def run_dosbox(root, conf, logfile, timeout):
    if logfile.exists():
        logfile.unlink()
    cmd = [str(machine("dosbox.exe")), "-conf", str(conf), "-silent", "-exit"]
    try:
        subprocess.run(cmd, cwd=str(root), timeout=timeout,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return "", "TIMEOUT -- dosbox-x did not exit"
    if not logfile.exists():
        return "", "no log produced -- the autoexec did not run"
    return logfile.read_text(encoding="latin1", errors="replace"), None


ERROR = re.compile(r"^([A-Z0-9_\\]+\.(?:PAS|INC))\((\d+)\): ((?:Error|Fatal).+)$",
                   re.M)


def report(build, out):
    """Print each failure with the source around it.

    The compiler prints the offending line but not its context, and the context
    is usually what identifies the fix.
    """
    shown = 0
    for m in ERROR.finditer(out):
        fname, line, msg = m.group(1), int(m.group(2)), m.group(3)
        print("")
        print("%s(%d): %s" % (fname, line, msg))
        f = build / fname
        if f.exists():
            src = f.read_text(encoding="latin1", errors="replace").splitlines()
            for n in range(max(1, line - 4), min(len(src), line + 2) + 1):
                print("  %s %4d %s" % (">>" if n == line else "  ", n,
                                       src[n - 1].rstrip()))
        shown += 1
    return shown


def install(cfg, root, build, targets):
    """Copy what just built into the directory the harnesses are run from.

    Staging wipes the build directory, so an executable only survives until the
    next build of anything else. Copying it by hand afterwards is easy to
    forget and, worse, easy to GET AWAY with: the run directory still holds the
    previous build under the same name, so it launches, behaves like the old
    code, and the change looks as though it did nothing.
    """
    spec = cfg["install"]
    if not spec:
        return
    try:
        run = root / (spec.get("to") or project.get("layout.built"))
    except project.Missing:
        return
    if not run.is_dir():
        print("  no %s -- nothing installed" % run)
        return
    products = outdir(cfg, build, keep=True)
    # `[install.as]` renames on the way out: STEM = "installed name". A DOS
    # compiler names its executable after the source and offers no way to say
    # otherwise, so a project whose shipped artefacts are called something a
    # compiler cannot produce -- NEUROSIS.001, an extension that is not even
    # .EXE -- has to rename at exactly this point. Naming it here rather than
    # renaming the SOURCE keeps the source called what the unit is called,
    # which is what every other instrument reads it by.
    as_named = cfg["install"].get("as", {})
    for t in targets:
        stem = t.split(".")[0]
        exe = products / (stem + ".EXE")
        if exe.exists():
            name = as_named.get(stem, exe.name)
            shutil.copy(exe, run / name)
            print("  installed %s/%s  (%d bytes)%s"
                  % (run.name, name, exe.stat().st_size,
                     "" if name == exe.name else "   <- %s" % exe.name))
    for pat in spec.get("alongside", []):
        for f in sorted(build.glob(pat)):
            shutil.copy(f, run / f.name)


