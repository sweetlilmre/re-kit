def main(argv):
    args = project.positionals(argv[1:], ("--compiler", "--timeout"))
    if not args:
        sys.stdout.write("usage: build.py CONFIG.toml [TARGET...] "
                         "[--selftest] [--keep] [--compiler NAME] [--sw=X]\n"
                         "       build.py CONFIG.toml --interactive\n")
        return 2

    def opt(name, default=None):
        flag = "--" + name
        return argv[argv.index(flag) + 1] if flag in argv else default

    cfg = read_config(args[0])
    root = pathlib.Path(args[0]).resolve().parent
    while not (root / "kit.toml").exists() and root != root.parent:
        root = root.parent

    selftest = "--selftest" in argv
    keep = "--keep" in argv
    compiler = opt("compiler") or cfg["compiler"].get("default") or "tp7"
    if compiler not in cfg["compiler"] or not isinstance(
            cfg["compiler"][compiler], dict):
        return project.complain("no compiler called %r in %s -- have %s"
                                % (compiler, args[0],
                                   ", ".join(k for k, v in cfg["compiler"].items()
                                             if isinstance(v, dict))))
    # `--sw=/$G-` appends to the recorded switch line, for testing one switch
    # against the binary without editing the configuration it is recorded in.
    extra = "".join(" " + a[5:] for a in argv if a.startswith("--sw="))
    selection = [a.upper().replace(".PAS", "") for a in args[1:]]

    build = root / cfg.get("build", "build")
    if cfg.get("subdir"):
        build = build / cfg["subdir"]

    # --interactive COMPILES NOTHING. It writes the mounts overlay and prints
    # the command, because the person who runs DOSBox interactively is the one
    # sitting in front of it. Writing the file is the part a tool can do without
    # a machine path reaching a committed file.
    if "--interactive" in argv:
        dosbox = cfg.get("dosbox", {})
        base = dosbox.get("base_conf")
        if not base:
            return project.complain(
                "%s has no [dosbox] base_conf, so there is no config to overlay"
                % args[0])
        out = root / (dosbox.get("overlay") or "MOUNTS.CFG")
        write_overlay(cfg, root, build, compiler, out)
        print("  wrote %s" % out)
        for line in out.read_text(encoding="ascii").split(NL):
            if line and not line.startswith("#"):
                print("      %s" % line)
        try:
            exe = machine("dosbox.exe")
        except project.Missing as exc:
            return project.complain(exc)
        # IT PRINTS AND DOES NOT LAUNCH. An interactive session belongs to the
        # person sitting in front of it, and their launcher is theirs to write:
        # for a DOSBox-X that wants its own directory as the working one, a
        # two-line batch file does that better than a flag here would.
        cmd = [str(exe), "-conf", str(root / base), "-conf", str(out)]
        print("\n  run it yourself -- the overlay goes SECOND, so its mounts "
              "run after the base file's autoexec:\n")
        print("  " + " ".join('"%s"' % c if " " in c else c for c in cmd))
        return 0

    # Lint FIRST where the project has a linter. The compiler reports a
    # nested-comment defect dozens of lines from its cause, so catching it here
    # saves a wild goose chase -- that has bitten this project three times.
    #
    # The linter's CHECKER is imported and run over the files about to be
    # staged, rather than the script being run as a command. That is not
    # fastidiousness: one repository's copy of `paslint.py` hardcodes a source
    # directory that does not exist there, so invoking it reports "0 problem(s)
    # in 0 file(s)" and passes. A check that cannot fail is worse than none,
    # and the script it replaces avoided this the same way.
    if cfg.get("lint") and not selftest:
        if lint_sources(root, cfg):
            print("build refused: fix the above first")
            return 2

    staged = stage(cfg, root, build, compiler, selftest, keep)
    if not staged:
        print("nothing staged")
        return 1
    targets = staged if selftest else ordered(cfg, build, staged, selection)
    write_batch(cfg, build, targets, compiler, extra, keep)
    conf = build / "DOSBUILD.CFG"
    write_conf(cfg, build, conf, compiler, root)

    print("compiler: %s%s" % (compiler, "  extra: " + extra if extra else ""))
    print("staged %d file(s) into %s: %s"
          % (len(targets), build.name, ", ".join(targets)))

    logname = cfg.get("log", "BUILD.LOG").split("\\")[-1]
    out, err = run_dosbox(root, conf, build / logname,
                          int(opt("timeout") or cfg.get("timeout", 180)))
    if err:
        print("FAILED:", err)
        return 1

    # A MISSING COMPILER IS A FAILED BUILD, and nothing downstream can tell.
    # See tool_missing: DOS leaves errorlevel at zero for a command it cannot
    # find, so the batch stamps ** OK and every other signal below agrees.
    missing_tool = tool_missing(
        machine("toolchain." + compiler, cfg["compiler"][compiler].get("exe")))
    if missing_tool:
        print("")
        print("BUILD FAILED -- the compiler is not there. %s does not exist on"
              % missing_tool)
        print("the mounted drive (dosbox.hdd). DOS does not set errorlevel for a")
        print("command it cannot find, so every unit would have been stamped")
        print("** OK and this build would have reported success without")
        print("compiling anything. Fix toolchain.%s in kit.local.toml."
              % compiler)
        return 1

    failed = report(build, out)

    # The batch file stamps ** FAILED / ** OK from the errorlevel after every
    # invocation. That verdict cannot be missed by a pattern, so it OVERRIDES
    # a clean parse: a compiler message without a filename -- "Error 49: Data
    # segment too large." is one -- matches nothing above and would otherwise
    # be reported as a successful build.
    # The DOS message, as a backstop for anything tool_missing cannot reach --
    # a tool on a drive that is not the mounted image, or a PATH lookup.
    # BOTH SPELLINGS. DOSBox-X prints "Bad command or filename" -- measured 4
    # Sep 2026 by pointing toolchain.tasm at a directory that does not exist,
    # which failed the build exit 1 and proved this backstop carries the
    # assembler, since tool_missing above covers only the compiler. MS-DOS
    # writes "Bad command or file name", and a build run under anything but
    # DOSBox-X would say that instead. Checking one spelling and quoting the
    # other in two comments is how a working guard gets "corrected" into one
    # that cannot fire.
    dos_lost = [l for l in out.rstrip().splitlines()
                if "Bad command or filename" in l
                or "Bad command or file name" in l]
    if dos_lost:
        print("")
        print("BUILD FAILED -- DOS could not run a command. The log says so and")
        print("errorlevel does not, which is why this is checked by text:")
        print("  " + dos_lost[0].strip())
        return 1

    stamped = out.count("** FAILED")
    if stamped and not failed:
        print("")
        print("The compiler reported failure but printed no FILE(LINE) error "
              "line, so there is no source context to show. The log's tail:")
        for line in out.rstrip().splitlines()[-12:]:
            print("  " + line)
        failed = stamped

    if failed:
        # THE VERDICT GOES LAST. `report` prints each error with a few lines of
        # source around it, so before this the final line of a failed build was
        # a fragment of somebody's `uses` clause -- and a failed build looks
        # exactly like a successful one to anyone reading the tail. Four
        # commits went by with a broken unit, a cascade into three more
        # targets, and stale executables being measured as if they were fresh.
        print("BUILD FAILED -- %d error(s) above. NOTHING WAS INSTALLED, so "
              "anything in the output directory is STALE and any measurement "
              "of it is meaningless." % failed)
        return 1
    ok = re.findall(r"^(\d+) lines,", out, re.M)
    if ok:
        print("all %d target(s) compiled: %s"
              % (len(ok), ", ".join(n + " lines" for n in ok)))
    else:
        print(out)
    install(cfg, root, build, targets)
    # AND WHAT A SELFTEST COST, said after the success line rather than before
    # it. stage() wipes the build directory, so a selftest leaves it holding
    # HELLO.* and nothing else: `artefact --check` then answers "cannot read a
    # side" and `routines` answers "nothing built", both correctly and neither
    # naming the cause. That is a check list going red for a reason nothing on
    # it can explain -- measured 4 Sep 2026 on two host roots, where the only
    # surviving evidence was HELLO.PAS sitting in build/.
    #
    # It goes HERE because a run that ends on "all 1 target(s) compiled" reads
    # as unqualified success, which is the shape the BUILD FAILED branch above
    # is careful to avoid.
    if selftest and not keep:
        print("the toolchain works. NOTE the build directory now holds only "
              "the self-test:\n"
              "  artefact --check, routines and linkbytes will fail until a "
              "real build is run.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
