# Ordering


USES = re.compile(r"(?is)\buses\b(.*?);")


def unit_deps(build, name83):
    """The 8.3 names a STAGED source depends on, from its `uses` clauses.

    Read from the staged copy, so the names have already been rewritten to
    their 8.3 form and match the filenames on disk. Units the compiler ships
    with -- Crt, Dos, System -- simply do not exist here and drop out.
    """
    p = build / name83
    if not p.exists():
        return []
    text = p.read_text(encoding="latin1", errors="replace")
    # strip comments, so a `uses` inside one cannot pull in a phantom
    text = re.sub(r"(?s)\{.*?\}|\(\*.*?\*\)", " ", text)
    out = []
    for clause in USES.findall(text):
        for word in re.split(r"[,\s]+", clause):
            cand = word.strip().upper()
            if cand and (build / (cand + ".PAS")).exists():
                out.append(cand + ".PAS")
    return out


def deps_first(build, sel):
    """`sel` plus everything it needs, units before the things that use them."""
    order, seen = [], set()

    def visit(name):
        if name in seen:
            return
        seen.add(name)
        for d in unit_deps(build, name):
            visit(d)
        order.append(name)

    for t in sel:
        visit(t)
    return order


def ordered(cfg, build, staged, selection):
    """The compile order, by whichever strategy the target declares.

    `uses` derives it from the staged sources and is right where the graph is
    the truth; `declared` takes the config's list verbatim and is right where a
    person has worked the order out against something the graph does not say --
    a circular reference broken by a bootstrap pass, for one.
    """
    sel = staged
    if selection:
        sel = [t for t in staged if t.split(".")[0] in selection]
        if not sel:
            raise SystemExit(
                "  no target matches %s; known: %s"
                % (selection, ", ".join(t.split(".")[0] for t in staged)))
    if cfg["order"]["mode"] == "declared":
        return sel
    return deps_first(build, sel)


# ---------------------------------------------------------------------------
# The batch file


def write_batch(cfg, build, targets, compiler, extra, keep):
    """Assembler first where a module exists, then the compiler per target.

    Every step appends to a log INSIDE the mounted drive, because DOSBox-X is a
    GUI application and writes nothing to the host's stdout. The log is read
    back from the host afterwards.
    """
    comp = cfg["compiler"][compiler]
    tpc = machine("toolchain." + compiler, comp.get("exe"))
    log = cfg.get("log", "BUILD.LOG")
    lines = ["@echo off"]
    if not keep and cfg.get("wipe_tpu", True):
        # Wiping from the host and wiping inside DOSBox are two erasures, and
        # a fix that did only the first left stale .TPUs behind.
        lines.append("del *.TPU > NUL")
    lines.append("echo === build > %s" % log)

    asm = cfg["assembler"]
    if asm.get("exe") or asm.get("flags"):
        tasm = machine("toolchain.tasm", asm.get("exe"))
        for name in sorted(p.name for p in build.glob("*.ASM")):
            lines.append("echo. >> %s" % log)
            lines.append("echo ---- %s >> %s" % (name, log))
            lines.append("%s %s %s >> %s"
                         % (tasm, asm.get("flags", ""), name, log))
            lines.append("if errorlevel 1 echo ** FAILED >> %s" % log)
            lines.append("if not errorlevel 1 echo ** OK >> %s" % log)

    switches = (comp.get("switches", "") + extra).strip()
    for t in targets:
        for pre in comp.get("prepass", []):
            # A pass emitted immediately BEFORE a named target, with its own
            # switches. It exists for a circular unit reference: whichever unit
            # compiles first needs the other's .TPU, so one of them is built
            # once in a cut-down form for the other to compile against. It has
            # to sit here rather than at the top of the batch, because the
            # cut-down unit still needs everything below it in the order.
            if pre["before"] != t:
                continue
            lines.append("echo. >> %s" % log)
            lines.append("echo ---- %s (%s) >> %s"
                         % (pre["target"], pre.get("why", "prepass"), log))
            lines.append("%s %s %s %s >> %s"
                         % (tpc, switches, pre.get("switches", ""),
                            pre["target"], log))
        lines.append("echo. >> %s" % log)
        lines.append("echo ---- %s >> %s" % (t, log))
        lines.append("%s %s %s >> %s" % (tpc, switches, t, log))
        lines.append("if errorlevel 1 echo ** FAILED >> %s" % log)
        lines.append("if not errorlevel 1 echo ** OK >> %s" % log)
    lines.append("exit")
    (build / "BUILD.BAT").write_text("\r\n".join(lines) + "\r\n",
                                     encoding="ascii")


def write_conf(cfg, build, conf, compiler):
    """The DOSBox-X config, generated so no machine path is ever committed."""
    comp = cfg["compiler"][compiler]
    conf.write_text(CONF_TEMPLATE.format(
        hdd=machine("dosbox.hdd"),
        build=str(build),
        drive=cfg.get("drive", "D"),
        title=cfg.get("title", "build"),
        binpath=comp.get("binpath", "C:\\TP\\BIN"),
    ), encoding="ascii")


