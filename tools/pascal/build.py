r"""Stage Pascal sources under 8.3 names, drive a real Turbo Pascal under
DOSBox-X, and read the compiler's output back.

    python kit/tools/pascal/build.py CONFIG.toml            everything
    python kit/tools/pascal/build.py CONFIG.toml VGA        one target
    python kit/tools/pascal/build.py CONFIG.toml --selftest prove the toolchain
    python kit/tools/pascal/build.py CONFIG.toml --compiler tp6
    python kit/tools/pascal/build.py CONFIG.toml --sw=/$G-  one extra switch

THREE SCRIPTS, ONE TOOL. `dosbuild.py`, `build.py` and `vtbuild.py` -- 993
lines across two repositories -- did the same six things: stage sources into a
DOS-visible directory under 8.3 names, order the targets so a unit precedes
whatever uses it, write a batch file, run DOSBox-X with a timeout, read the log
back from the host, and install what came out. What differed was DATA, and it
is now a config file per target (psycho issue #35).

**A NOTE ON THE WORD.** The ticket calls this a build harness. `harness` is
taken: in this method's vocabulary it is a small program that runs one piece of
the SUBJECT so a person can watch it -- `TPART3.EXE` is a harness. This is the
thing that BUILDS those, so it is `build.py`. See `kit/wiki/CONTEXT.md`.

THE DOSBOX CONFIG IS GENERATED, ALWAYS, and that is a fix rather than a
preference. Two of the three scripts pointed at a committed `.conf` holding
`D:\source\psycho\build` and `D:\DOSBox-X\Machine\HDD` -- machine paths in a
committed file, which the standing rules forbid outright. The third already
generated its own. Generating it puts every machine path in `kit.local.toml`
where it belongs, and makes the mount agree with the staging directory by
construction rather than by somebody remembering.

WHAT IS PASSED IN, never built in: the compiler and its switch line, the
assembler and its flags, the 8.3 name map, the ordering strategy, the source
encoding, the dialect, the target list and where the result is installed. The
switch line is the one to be careful with, because getting it wrong does not
fail -- it produces a build that MEASURES wrong. TP7 defaults stack checking
ON, and with it on every framed procedure, INCLUDING an `assembler` one, opens
with a seven-byte `XOR AX,AX / CALLF` before the body; leaving the default made
every hand-transcribed routine differ from the binary in its opening bytes.

WHAT IS NOT COMPARABLE AFTERWARDS. `.TPU` and `.OBJ` files embed a timestamp,
so two builds of identical source do not hash the same. Measured: across two
consecutive full builds of this demo, all 243 staged and built files differ in
three places and **all 35 `.EXE` files are byte-identical**. So an executable
is the unit of a reproducibility check here, and a `.TPU` never is -- which is
why the unit instruments compare a `.TPU`'s CODE section rather than its bytes.
"""
