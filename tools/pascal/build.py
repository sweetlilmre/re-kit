def dos_text(text, encoding):
    """The source as the DOS compiler will see it.

    `binary` copies bytes untouched, which is what a release tree of latin-1
    sources with accented comments needs. Everything else round-trips through
    the named encoding so a character the compiler cannot read becomes visible
    here rather than as an error forty lines from its cause.
    """
    if encoding in ("binary", "bytes"):
        return text
    return text.encode(encoding, errors="replace").decode(encoding)


def tp6_dialect(text, restore="{$F-}"):
    """Replace an interface's `far` directives with an `{$F+}` region.

    A COMPILER FACT, not a project's, which is why it travels: Turbo Pascal 6
    has no `far` directive on a unit's exported routines at all. It rejects one
    on the interface declaration (error 73) and on the implementation header of
    a routine the interface already declared (error 36). The calling model comes
    from `{$F}` at the point of declaration and nowhere else; TP7 relaxed that.

    So the rewrite is a SWITCH rather than a moved directive -- `{$F+}` after
    the interface keyword, restored at the implementation keyword. That keeps
    the interface's routines far and the implementation's private ones near,
    which is the TP7 shape. Turning `{$F+}` on for the whole unit would promote
    the private routines too.
    """
    tail = r"(?:\s*\([^()]*\))?(?:\s*:\s*\w+)?\s*;"
    iface = re.search(r"(?im)^interface\b[ \t]*$", text)
    impl = re.search(r"(?im)^implementation\b", text)
    if not (iface and impl):
        return text
    head, body = text[: impl.start()], text[impl.start():]
    n = 0

    def strip(m):
        nonlocal n
        n += 1
        return m.group(1)

    # The declaration is matched WHOLE rather than up to the first semicolon: a
    # parameter list separates its groups with semicolons too, so `[^;]*` stops
    # short on every routine taking more than one group.
    head = re.sub(r"(?is)(\b(?:procedure|function)\s+\w+\b" + tail +
                  r")\s*far\s*;", strip, head)
    if not n:
        return text                       # nothing exported far -- leave alone
    head = head[: iface.end()] + "\n{$F+}" + head[iface.end():]
    return head + body.replace("implementation", "implementation\n" + restore, 1)


DIALECTS = {"": lambda t: t, "tp7": lambda t: t, "tp6": tp6_dialect}


def rename_source(text, name83, names):
    """Rewrite the unit name, `uses` clauses and `{$I}` paths for 8.3 DOS.

    The unit identifier inside a file is independent of the filename, but the
    compiler finds a unit BY FILENAME -- so `uses Part3Sprites` has to become
    `uses P3Sprite` the moment PART3_SPRITES.PAS is staged as P3SPRITE.PAS.
    """
    row = names.get(name83)
    if not row:
        return text
    _, unit_old, unit_new = row
    text = re.sub(r"(?im)^(\s*unit\s+)%s(\s*;)" % re.escape(unit_old),
                  r"\g<1>%s\g<2>" % unit_new, text)
    # NOT INSIDE A STRING LITERAL. This is a case-insensitive \bword\b sweep
    # over the whole file, so a map row like PSYCHO.PAS -> Psycho rewrote the
    # literal in ShowString(' MEGADEMO, PSYCHO NEUROSIS!!! ') to `Psycho` and
    # changed the demo's own banner text -- a 3-byte coverage span that reading
    # the source could never explain, because the source was right and the
    # staged copy was not. Comments are skipped for the same reason in reverse:
    # rewriting them makes the staged file lie about where it came from.
    parts = re.split(r"('(?:''|[^'])*'|\{[^}]*\}|\(\*.*?\*\))", text, flags=re.S)
    for i in range(0, len(parts), 2):           # even indices are code
        for _, old, new in names.values():
            parts[i] = re.sub(r"(?i)\b%s\b" % re.escape(old), new, parts[i])
    text = "".join(parts)
    # {$I gen/P3PAL.INC} -> {$I GEN\P3PAL.INC}
    text = re.sub(r"(?i)\{\$I\s+([a-z0-9_]+)/([A-Z0-9_]+\.INC)\s*\}",
                  lambda m: "{$I %s\\%s}" % (m.group(1).upper(), m.group(2)),
                  text)
    return text


def wipe(d, keep=False):
    d.mkdir(parents=True, exist_ok=True)
    if keep:
        return
    for f in d.glob("*"):
        if f.is_file():
            f.unlink()


def stage(cfg, root, build, compiler, selftest=False, keep=False):
    """Put everything the compiler needs into the mounted directory.

    Returns the staged target filenames, in config order. `keep` leaves what is
    already there -- see the note on it in `main`.
    """
    wipe(build, keep)
    if selftest:
        (build / "HELLO.PAS").write_text(SELFTEST, encoding="ascii")
        return ["HELLO.PAS"]

    st = cfg["stage"]
    enc = st["encoding"]
    names = {k: tuple(v) for k, v in cfg["names"].items()}
    src = root / cfg.get("src", "src")
    # Sources whose 8.3 name and unit identifier are ALREADY right map to
    # themselves. Generated test harnesses are the case this exists for: they
    # are emitted with conforming names, so listing each one here would be a
    # second copy of a fact their generator already guarantees, and it would go
    # stale the first time somebody added one.
    identity = []
    for pat in st.get("identity", []):
        for f in sorted(src.glob(pat)):
            if f.name not in names:
                names[f.name] = (f.name, f.stem, f.stem)
                identity.append(f.name)
    dialect = DIALECTS[cfg["compiler"][compiler].get("dialect", "")]

    # Include directories staged as subdirectories of the mounted drive, so a
    # rewritten `{$I GEN\X.INC}` resolves. Each entry is `name = "path"`.
    for sub, rel in sorted(st.get("subdirs", {}).items()):
        out = build / sub.upper()
        wipe(out, keep)
        for f in sorted((root / rel).glob("*")):
            if f.is_file():
                shutil.copy(f, out / f.name.upper())

    # Files that travel beside the sources but are not compiled in their own
    # right: assembler modules, includes, object modules, data. Copied flat
    # into the build root, because the assembler resolves INCLUDE relative to
    # the current directory and the compiler looks for a `{$L}` object next to
    # the unit that links it.
    for pat in st.get("alongside", []):
        for f in sorted(root.glob(pat)):
            if f.is_file():
                shutil.copy(f, build / f.name.upper())

    staged = []
    order = list(cfg["order"].get("list") or [])
    if not order:
        order = sorted(names) or sorted(p.name for p in src.glob("*.PAS"))
    # Identity-mapped sources are appended AFTER the declared list, the way the
    # script this replaces appended them to its name map. They are leaves that
    # nothing else uses, so where they sit only matters in that they must be
    # staged at all -- and leaving them out of the order silently built 38
    # targets instead of 67, with every one that ran reporting success.
    order += [n for n in identity if n not in order]
    for name in order:
        p = src / name
        if not p.exists():
            continue                      # not transcribed yet -- skip quietly
        name83 = names.get(name, (name,))[0]
        if enc in ("binary", "bytes"):
            shutil.copy(p, build / name83.upper())
        else:
            text = p.read_text(encoding="utf-8", errors="replace")
            text = rename_source(text, name, names) if names else text
            text = dialect(text)
            (build / name83.upper()).write_text(dos_text(text, enc),
                                                encoding=enc, errors="replace")
        staged.append(name83.upper())
    return staged


