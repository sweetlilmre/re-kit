# Running, reporting, installing


def run_dosbox(root, conf, logfile, timeout):
    if logfile.exists():
        logfile.unlink()
    cmd = [str(machine("dosbox.exe")), "-conf", str(conf), "-silent", "-exit"]
    try:
        subprocess.run(cmd, cwd=str(root), timeout=timeout,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return "", "TIMEOUT -- dosbox-x did not exit"
    if not logfile.exists():
        return "", "no log produced -- the autoexec did not run"
    return logfile.read_text(encoding="latin1", errors="replace"), None


ERROR = re.compile(r"^([A-Z0-9_\\]+\.(?:PAS|INC))\((\d+)\): ((?:Error|Fatal).+)$",
                   re.M)


def report(build, out):
    """Print each failure with the source around it.

    The compiler prints the offending line but not its context, and the context
    is usually what identifies the fix.
    """
    shown = 0
    for m in ERROR.finditer(out):
        fname, line, msg = m.group(1), int(m.group(2)), m.group(3)
        print("")
        print("%s(%d): %s" % (fname, line, msg))
        f = build / fname
        if f.exists():
            src = f.read_text(encoding="latin1", errors="replace").splitlines()
            for n in range(max(1, line - 4), min(len(src), line + 2) + 1):
                print("  %s %4d %s" % (">>" if n == line else "  ", n,
                                       src[n - 1].rstrip()))
        shown += 1
    return shown


def install(cfg, root, build, targets):
    """Copy what just built into the directory the harnesses are run from.

    Staging wipes the build directory, so an executable only survives until the
    next build of anything else. Copying it by hand afterwards is easy to
    forget and, worse, easy to GET AWAY with: the run directory still holds the
    previous build under the same name, so it launches, behaves like the old
    code, and the change looks as though it did nothing.
    """
    spec = cfg["install"]
    if not spec:
        return
    try:
        run = root / (spec.get("to") or project.get("layout.built"))
    except project.Missing:
        return
    if not run.is_dir():
        print("  no %s -- nothing installed" % run)
        return
    for t in targets:
        exe = build / (t.split(".")[0] + ".EXE")
        if exe.exists():
            shutil.copy(exe, run / exe.name)
            print("  installed %s/%s  (%d bytes)"
                  % (run.name, exe.name, exe.stat().st_size))
    for pat in spec.get("alongside", []):
        for f in sorted(build.glob(pat)):
            shutil.copy(f, run / f.name)


