# The config, and the answers behind it


def read_config(path):
    with io.open(path, "rb") as fh:
        cfg = tomllib.load(fh)
    cfg.setdefault("order", {}).setdefault("mode", "uses")
    cfg.setdefault("stage", {}).setdefault("encoding", "ascii")
    cfg.setdefault("names", {})
    cfg.setdefault("assembler", {})
    cfg.setdefault("install", {})
    if "compiler" not in cfg:
        raise SystemExit("  %s: no [compiler] section" % path)
    return cfg


def machine(key, fallback=None):
    """A machine path, from kit.local.toml. Never from a committed file."""
    try:
        return project.get(key)
    except project.Missing:
        if fallback is not None:
            return fallback
        raise


