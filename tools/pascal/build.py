def lint_sources(root, cfg):
    """Run the project's own Pascal checker over the sources it is about to
    build. Returns the number of problems, having printed them.

    `lint` names the script; its `check(path)` is imported and called. The
    files are the config's own order plus whatever the identity globs pick up,
    so the check covers exactly what the build covers -- no more, and never
    less because a directory constant pointed somewhere else.
    """
    spec = cfg["lint"]
    script = spec if isinstance(spec, str) else spec.get("script")
    sys.path.insert(0, str((root / script).parent))
    try:
        mod = __import__(pathlib.Path(script).stem)
        check = getattr(mod, "check")
    except Exception as exc:              # absent, unimportable, or no check()
        print("  linter %s unavailable (%s) -- NOT skipped silently" % (script, exc))
        return 0
    src = root / cfg.get("src", "src")
    wanted = list(cfg["order"].get("list") or [])
    for pat in cfg["stage"].get("identity", []):
        wanted += [f.relative_to(src).as_posix()
                   for f in sorted(src.glob(pat))
                   if f.relative_to(src).as_posix() not in wanted]
    if not wanted:
        wanted = sorted(p.relative_to(src).as_posix() for p in src.rglob("*.PAS"))
    total = 0
    for name in wanted:
        f = src / name
        if not f.exists():
            continue
        probs = check(f)
        if probs:
            print("")
            print("=== %s ===" % f.name)
            for ln, msg in probs:
                print("  line %4d  %s" % (ln, msg))
            total += len(probs)
    return total


